CREATE TABLE `prospect_visits` (
  `id` CHAR(36) NOT NULL,
  `prospect_id` CHAR(36) NOT NULL,
  `sales_executive_id` CHAR(36) NOT NULL,
  `check_in_at` DATETIME(6) NOT NULL,
  `check_in_latitude` DOUBLE NOT NULL,
  `check_in_longitude` DOUBLE NOT NULL,
  `check_out_at` DATETIME(6) NULL,
  `check_out_latitude` DOUBLE NULL,
  `check_out_longitude` DOUBLE NULL,
  `selfie_reference` VARCHAR(2048) NOT NULL DEFAULT '',
  `visit_notes` TEXT NOT NULL DEFAULT (''),
  `follow_up_notes` TEXT NOT NULL DEFAULT (''),
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `open_visit_prospect_id` CHAR(36) GENERATED ALWAYS AS (CASE WHEN `check_out_at` IS NULL THEN `prospect_id` ELSE NULL END) STORED,
  PRIMARY KEY (`id`),
  KEY `prospect_visits_prospect_id_check_in_at_idx` (`prospect_id`, `check_in_at`),
  KEY `prospect_visits_sales_executive_id_check_in_at_idx` (`sales_executive_id`, `check_in_at`),
  UNIQUE KEY `prospect_visits_one_open_visit_idx` (`open_visit_prospect_id`),
  CONSTRAINT `prospect_visits_prospect_id_fkey` FOREIGN KEY (`prospect_id`) REFERENCES `prospects` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `prospect_visits_sales_executive_id_fkey` FOREIGN KEY (`sales_executive_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

