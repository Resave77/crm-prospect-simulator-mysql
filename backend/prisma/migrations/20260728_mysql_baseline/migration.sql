CREATE TABLE `users` (
  `id` CHAR(36) NOT NULL,
  `email` VARCHAR(191) NOT NULL,
  `password_hash` VARCHAR(255) NOT NULL,
  `full_name` VARCHAR(255) NOT NULL,
  `role` ENUM('ADMINISTRATOR', 'SALES_EXECUTIVE') NOT NULL,
  `status` ENUM('ACTIVE', 'INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  `token_version` INT NOT NULL DEFAULT 1,
  `last_login_at` DATETIME(6) NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`id`),
  UNIQUE KEY `users_email_key` (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `refresh_sessions` (
  `id` CHAR(36) NOT NULL,
  `user_id` CHAR(36) NOT NULL,
  `token_hash` VARCHAR(255) NOT NULL,
  `user_agent` VARCHAR(512) NOT NULL DEFAULT '',
  `ip_address` VARCHAR(45) NOT NULL DEFAULT '',
  `expires_at` DATETIME(6) NOT NULL,
  `revoked_at` DATETIME(6) NULL,
  `revoke_reason` VARCHAR(255) NULL,
  `replaced_by_session_id` CHAR(36) NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`id`),
  KEY `refresh_sessions_user_id_expires_at_idx` (`user_id`, `expires_at`),
  KEY `refresh_sessions_expires_at_idx` (`expires_at`),
  CONSTRAINT `refresh_sessions_user_id_fkey` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `prospects` (
  `id` CHAR(36) NOT NULL,
  `google_place_id` VARCHAR(191) NOT NULL,
  `place_name` VARCHAR(255) NOT NULL,
  `formatted_address` TEXT NOT NULL,
  `latitude` DOUBLE NULL,
  `longitude` DOUBLE NULL,
  `place_category` VARCHAR(191) NOT NULL,
  `industry_group` VARCHAR(191) NOT NULL DEFAULT 'Other',
  `place_types` JSON NOT NULL DEFAULT (JSON_ARRAY()),
  `phone_number` VARCHAR(64) NULL,
  `website_url` VARCHAR(2048) NULL,
  `google_maps_url` VARCHAR(2048) NULL,
  `assigned_sales_executive_id` CHAR(36) NOT NULL,
  `visit_notes` TEXT NOT NULL DEFAULT (''),
  `follow_up_notes` TEXT NOT NULL DEFAULT (''),
  `status` ENUM('NEW_LEAD', 'CONTACTED', 'INTERESTED', 'QUALIFIED', 'PROPOSAL_SENT', 'NEGOTIATION', 'WON', 'LOST', 'CONVERTED') NOT NULL DEFAULT 'NEW_LEAD',
  `converted_at` DATETIME(6) NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`id`),
  UNIQUE KEY `prospects_google_place_id_key` (`google_place_id`),
  KEY `prospects_assigned_sales_executive_id_status_idx` (`assigned_sales_executive_id`, `status`),
  KEY `prospects_status_created_at_idx` (`status`, `created_at`),
  KEY `prospects_industry_group_status_idx` (`industry_group`, `status`),
  CONSTRAINT `prospects_assigned_sales_executive_id_fkey` FOREIGN KEY (`assigned_sales_executive_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `prospect_status_history` (
